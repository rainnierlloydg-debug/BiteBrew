import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';

if (fs.existsSync('.env')) process.loadEnvFile('.env');
const database = process.env.TEST_DATABASE_URL;
test('one login identifies every role and staff accounts are created only by the owner', { skip: !database || database.includes('CHANGE_ME'), timeout: 60000 }, async t => {
  assert.ok(new URL(database).pathname.endsWith('_test'));
  assert.notEqual(database, process.env.DATABASE_URL);
  process.env.DATABASE_URL = database;
  const migration = spawnSync(process.execPath, ['node_modules/prisma/build/index.js', 'migrate', 'deploy'], { env: process.env, stdio: 'pipe' });
  assert.equal(migration.status, 0);
  const [{ createApplication }, { db }, { hashPassword }] = await Promise.all([import('../server/app.js'), import('../server/db.js'), import('../server/lib/password.js')]);
  const deliveredCodes = new Map();
  const app = await createApplication({ jobs: false, verificationOptions: { send: async ({ email, code }) => deliveredCodes.set(email, code) } });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + app.server.address().port, suffix = randomUUID().slice(0, 8), password = 'Fixture staff password ' + suffix;
  const email = `signup-${suffix}@example.test`, rejectedEmail = `reject-${suffix}@example.test`;
  const owner = await db.user.create({ data: { name: 'DEMONSTRATION signup owner', email: `signup-owner-${suffix}@example.test`, role: 'OWNER', passwordHash: await hashPassword(password) } });
  const reviewer = await db.user.create({ data: { name: 'DEMONSTRATION cashier reviewer', email: `signup-cashier-${suffix}@example.test`, role: 'CASHIER', passwordHash: await hashPassword(password) } });
  t.after(async () => {
    const users = await db.user.findMany({ where: { email: { in: [email, rejectedEmail, owner.email, reviewer.email] } }, select: { id: true } });
    const ids = users.map(user => user.id);
    await db.session.deleteMany({ where: { userId: { in: ids } } });
    await db.auditLog.deleteMany({ where: { actorId: { in: ids } } });
    await db.idempotency.deleteMany({ where: { userId: { in: ids } } });
    await db.user.deleteMany({ where: { id: { in: ids } } });
    const accounts = await db.customerAccount.findMany({ where: { email: { in: [rejectedEmail, owner.email] } }, select: { id: true, customerId: true } });
    await db.customerAccount.deleteMany({ where: { id: { in: accounts.map(row => row.id) } } });
    await db.customer.deleteMany({ where: { id: { in: accounts.map(row => row.customerId) } } });
    await app.close();
  });
  function client() {
    return { cookie: '', csrf: '', async request(route, { method = 'GET', data, status = 200, csrf = true, key = randomUUID() } = {}) {
      if (route === '/customer/register' && data && !Object.hasOwn(data, 'confirmPassword')) data = { ...data, confirmPassword: data.password };
      const response = await fetch(base + '/api' + route, { method, headers: { Cookie: this.cookie, 'Content-Type': 'application/json', ...(csrf ? { 'X-CSRF-Token': this.csrf } : {}), 'X-Operation-ID': key }, body: data ? JSON.stringify(data) : undefined });
      const cookie = response.headers.getSetCookie()[0]; if (cookie) this.cookie = cookie.split(';')[0];
      const result = await response.json(); assert.equal(response.status, status, route + ': ' + JSON.stringify(result.error)); if (result.data?.csrf) this.csrf = result.data.csrf; if (result.data?.verificationRequired) return this.request('/customer/register/verify', { method: 'POST', data: { token: result.data.token, code: deliveredCodes.get(result.data.email) } }); return result;
    } };
  }
  const guest = client(), admin = client(), cashier = client(), customer = client();
  await guest.request('/session');
  const defaultPassword = 'ellapizza12345678';
  const details = { name: 'DEMONSTRATION admin-created staff', email, role: 'KITCHEN', active: true };
  await guest.request('/staff/register', { method: 'POST', data: details, status: 410 });
  assert.equal(await db.user.count({ where: { email } }), 0);
  await guest.request('/staff', { method: 'POST', data: details, status: 401 });
  await admin.request('/session');
  const adminLogin = (await admin.request('/login', { method: 'POST', data: { email: owner.email, password } })).data;
  assert.equal(adminLogin.accountType, 'OWNER'); assert.equal(adminLogin.redirectTo, '/staff.html?page=dashboard');
  await cashier.request('/session');
  const cashierLogin = (await cashier.request('/login', { method: 'POST', data: { email: reviewer.email, password } })).data;
  assert.equal(cashierLogin.accountType, 'CASHIER'); assert.equal(cashierLogin.redirectTo, '/staff.html?page=pos');
  await cashier.request('/staff', { method: 'POST', data: details, status: 403 });
  const key = randomUUID();
  const created = (await admin.request('/staff', { method: 'POST', data: details, key })).data;
  await admin.request('/staff', { method: 'POST', data: details, key });
  assert.equal(await db.user.count({ where: { email } }), 1);
  assert.equal((await db.user.findUnique({where:{id:created.id}})).registrationPending, false); assert.equal(created.passwordHash, undefined);
  const kitchenLogin = (await guest.request('/login', { method: 'POST', data: { email, password: defaultPassword } })).data;
  assert.equal(kitchenLogin.user.role, 'KITCHEN'); assert.equal(kitchenLogin.redirectTo, '/staff.html?page=kitchen');
  await guest.request('/staff', { status: 403 }); await guest.request('/customer/profile', { status: 401 });
  await customer.request('/session');
  await customer.request('/customer/register', { method: 'POST', data: { name: 'DEMONSTRATION buyer', contact: '', email: owner.email, password }, status: 409 });
  const registered = (await customer.request('/customer/register', { method: 'POST', data: { name: 'DEMONSTRATION buyer', contact: '', email: rejectedEmail, password } })).data.customer;
  await customer.request('/customer/logout', { method: 'POST', data: {} });
  const buyerLogin = (await customer.request('/login', { method: 'POST', data: { email: rejectedEmail, password } })).data;
  assert.equal(buyerLogin.accountType, 'CUSTOMER'); assert.equal(buyerLogin.user, null); assert.equal(buyerLogin.customer.id, registered.id);
  await customer.request('/staff', { status: 401 }); await customer.request('/orders', { status: 401 });
  assert.equal((await customer.request('/session')).data.customer.id, registered.id);
  await admin.request('/staff', { method: 'POST', data: { ...details, email: rejectedEmail }, status: 422 });
  const switched = (await customer.request('/login', { method: 'POST', data: { email: owner.email, password } })).data;
  assert.equal(switched.user.id, owner.id); await customer.request('/customer/profile', { status: 401 });
  await customer.request('/login', { method: 'POST', data: { email: rejectedEmail, password } });
  await customer.request('/staff', { status: 401 });
  await customer.request('/login', { method: 'POST', data: { email: rejectedEmail, password: 'Incorrect fixture password' }, status: 401 });
  await db.user.update({ where: { id: created.id }, data: { active: false } });
  await customer.request('/login', { method: 'POST', data: { email, password: defaultPassword }, status: 401 });
  await customer.request('/login', { method: 'POST', data: { email: rejectedEmail, password, role: 'OWNER' }, status: 422 });
  await db.customerAccount.create({ data: { email: owner.email, passwordHash: owner.passwordHash, customer: { create: { name: 'DEMONSTRATION ambiguous account' } } } });
  await customer.request('/login', { method: 'POST', data: { email: owner.email, password }, status: 401 });
});
